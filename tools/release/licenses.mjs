// Stages the licence folder that electron-builder.yml copies to resources/licenses/:
//   LICENSE.txt            Wicaby's LICENSE (the GPL-3.0 text)
//   THIRD_PARTY_NOTICES.md
//   GPL-2.0.txt, LGPL-2.1.txt  the texts that cover mpv and the libraries linked into it
//   libarchive-wasm.txt    libarchive-wasm and the C libraries in its .wasm (the package ships no licence file)
//   npm-licenses.txt       the licence of every npm package the desktop sources import, and of
//                          their dependencies, read from node_modules
//
//   node tools/release/licenses.mjs [outDir]   (default: apps/desktop/out/licenses)
import fs from 'node:fs';
import { isBuiltin } from 'node:module';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', '..');
const desktop = path.join(root, 'apps', 'desktop');
const out = path.resolve(process.argv[2] ?? path.join(desktop, 'out', 'licenses'));

// Bare imports in the desktop sources ('svelte/easing' -> svelte, '@lucide/svelte' stays whole).
const roots = new Set();
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(ts|js|mjs|svelte)$/.test(e.name)) {
      // Statements only: `import … from 'x'`, `import 'x'`, a `} from 'x'` line, `import('x')`.
      const re = /(?:^\s*import\b[^'"\n]*|^\s*\}\s*from\s*|\bimport\(\s*)['"]((?:@[\w.-]+\/)?\w[\w.-]*(?:\/[\w./-]*)?)['"]/gm;
      for (const [, spec] of fs.readFileSync(p, 'utf8').matchAll(re)) {
        const name = spec.split('/').slice(0, spec.startsWith('@') ? 2 : 1).join('/');
        // electron is the runtime itself; its licence ships as LICENSE.electron.txt.
        if (!isBuiltin(spec) && name !== 'electron') roots.add(name);
      }
    }
  }
};
walk(path.join(desktop, 'src'));
// Never imported, but its headers are compiled into the shipped Linux addon (out/native/wicaby_mpv.node).
if (fs.existsSync(path.join(desktop, 'native', 'mpv-render', 'binding.gyp'))) roots.add('node-addon-api');

// Node's lookup: <dir>/node_modules/<name>, then each parent up to the repo root.
function find(name, from) {
  for (let d = from; d.startsWith(root); d = path.dirname(d)) {
    const p = path.join(d, 'node_modules', name);
    if (fs.existsSync(path.join(p, 'package.json'))) return p;
  }
  return null;
}

const seen = new Map(); // dir -> package.json
const visit = (name, from, required) => {
  const dir = find(name, from);
  if (!dir) {
    // Optional and platform-only dependencies may be absent; an imported package may not.
    if (required) throw new Error(`${name} is imported by apps/desktop/src but not installed`);
    return;
  }
  if (seen.has(dir)) return;
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  seen.set(dir, pkg);
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir, false);
};
for (const name of roots) visit(name, desktop, true);

const rule = '='.repeat(80);
const sections = [...seen]
  .sort(([, a], [, b]) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
  .map(([dir, pkg]) => {
    const files = fs.readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)([.-].*)?$/i.test(f)).sort();
    const texts = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim());
    const spdx = typeof pkg.license === 'string' ? pkg.license : 'see package';
    return `${rule}\n${pkg.name} ${pkg.version} (${spdx})\n${rule}\n\n${texts.join('\n\n') || `No licence file in the package; package.json declares ${spdx}.`}\n`;
  });

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
fs.copyFileSync(path.join(root, 'LICENSE'), path.join(out, 'LICENSE.txt'));
fs.copyFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), path.join(out, 'THIRD_PARTY_NOTICES.md'));
for (const f of ['GPL-2.0.txt', 'LGPL-2.1.txt', 'libarchive-wasm.txt']) fs.copyFileSync(path.join(import.meta.dirname, 'licenses', f), path.join(out, f));
fs.writeFileSync(
  path.join(out, 'npm-licenses.txt'),
  `Licence texts of the npm packages that Wicaby for Windows imports, and of their dependencies\n(some, like the Svelte compiler's, are only used at build time).\nGenerated by tools/release/licenses.mjs from node_modules.\n\n${sections.join('\n')}`,
);
console.log(`${out}: ${seen.size} npm packages (${[...roots].sort().join(', ')} and their dependencies)`);
